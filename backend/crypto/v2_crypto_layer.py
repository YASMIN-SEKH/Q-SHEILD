def apply_fusion(df_in: pd.DataFrame) -> pd.Series:
    """Returns probability of genuine class (0-1)."""
    return pd.Series(
        fusion_lr.predict_proba(df_in[Z_SCORE_COLS].values)[:, 1],
        index=df_in.index
    )

