def reconstruction_error(model, sequences: np.ndarray) -> np.ndarray:
    """Mean absolute error per sequence."""
    if len(sequences) == 0:
        return np.array([])
    preds = model.predict(sequences, verbose=0)
    return np.mean(np.abs(preds - sequences), axis=(1, 2))


