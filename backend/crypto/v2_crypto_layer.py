# ============================================================
# SECTION 57 — Step 3: Feature Extraction
#              Step 4: Generate Behavioral Signature
# ============================================================
# Feature extraction reuses extract_features() from Phase 6.
# Behavioral signature = (fused_fidelity_score, recon_error)
# computed on the current window against the enrolled template.

def generate_behavioral_signature(
    window_df       : pd.DataFrame,
    claimed_subject : str,
) -> dict:
    """
    Steps 3 & 4 — Feature Extraction + Generate Behavioral Signature.

    Returns
    -------
    dict:
      'fused_score'      — quantum fidelity against enrolled template
      'recon_error'      — LSTM reconstruction error (anomaly signal)
      'anomaly_zone'     — 'normal' | 'elevated' | 'high'
      'fidelity_ip'      — inner-product fidelity (raw)
      'fidelity_bc'      — Bhattacharyya fidelity (raw)
      'llr'              — XGBoost LLR score
    """
    if len(window_df) < MIN_WINDOW_ROWS:
        return None   # not enough data yet

    # Step 3: Feature extraction
    fft_enc   = fft_encode(window_df)

    # Step 4a: Quantum state → fidelity
    probe_psi    = build_unified_state_vector(window_df)
    template_psi = enrolled_templates[claimed_subject]

