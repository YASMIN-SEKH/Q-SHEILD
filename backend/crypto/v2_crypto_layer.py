# SECTION 26 — Step 3: Validate Integrity
# ============================================================
# Three-layer integrity check before ANY write:
#  [A] ML-DSA signature over (KEM-ct || enc-template)
#  [B] SHA-256 of the encrypted template blob
#  [C] Metadata sanity (version, dimension, norm bounds)

def validate_integrity(bundle: dict) -> dict:
    """
    Step 3 — Validate Integrity.
    Returns a dict of validation results; raises on any failure.
    """
    meta     = bundle['metadata']
    subject  = meta['subject']
    results  = {'subject': subject, 'checks': {}}

    enc_bytes = bytes.fromhex(bundle['encrypted_template_hex'])
    kem_ct    = bytes.fromhex(bundle['kem_ciphertext_hex'])
    vk_bytes  = bytes.fromhex(bundle['dsa_verify_key_hex'])
    sig_bytes = bytes.fromhex(bundle['dsa_signature_hex'])

    # ── Check A: ML-DSA Signature ──────────────────────────
    msg_to_verify = kem_ct + enc_bytes
    sig_valid = dsa_verify(vk_bytes, msg_to_verify, sig_bytes)
    results['checks']['ml_dsa_signature'] = sig_valid
    if not sig_valid:
        raise ValueError(f'[{subject}] ML-DSA signature INVALID — rejecting bundle')
    print(f'  [A] ML-DSA signature       : VALID ✓')

    # ── Check B: Ciphertext hash ────────────────────────────
    ct_sha256 = hashlib.sha256(enc_bytes).hexdigest()
    results['checks']['ciphertext_sha256'] = ct_sha256
    print(f'  [B] Ciphertext SHA-256     : {ct_sha256[:24]}...')

    # ── Check C: Metadata sanity ────────────────────────────
    dim  = meta.get('template_dim', 0)
    norm = meta.get('template_norm', 0.0)
    assert 50 <= dim <= 512,    f'template_dim={dim} outside expected range [50,512]'
    assert 0.99 <= norm <= 1.01, f'template_norm={norm:.6f} not unit-norm'
    results['checks']['metadata_sane'] = True
    print(f'  [C] Metadata sanity        : PASS ✓')
    print(f'       template_dim={dim}  template_norm={norm:.8f}')

    results['ct_sha256'] = ct_sha256
    results['enc_bytes'] = enc_bytes     # carry forward to storage
    results['kem_ct']    = kem_ct

    print(f'Step 3 — Integrity Validated for {subject} ✓')
    return results


