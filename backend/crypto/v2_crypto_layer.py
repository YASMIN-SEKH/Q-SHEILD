# SECTION 47 — Authentication Decision Logic
# ============================================================
#
# Gate 1 — Fidelity High?
#   fused_score >= per_subject_thr  →  YES (proceed to Gate 2)
#   fused_score <  per_subject_thr  →  NO  →  REJECT_SESSION
#
# Gate 2 — Anomaly Low?
#   mean_recon_error <= ANOMALY_THR_STEPUP  →  YES  →  ACCESS_GRANTED
#   ANOMALY_THR_STEPUP < err <= ANOMALY_THR_REJECT  →  STEP_UP_AUTH
#   mean_recon_error >  ANOMALY_THR_REJECT  →  REJECT_SESSION

@dataclass
class AuthResult:
    subject_id       : str
    session_idx      : int
    decision         : AuthDecision
    fused_score      : float
    fidelity_thr     : float
    fidelity_pass    : bool
    mean_recon_error : float
    anomaly_zone     : str
    llr              : float
    fidelity_ip      : float
    fidelity_bc      : float
    elapsed_ms       : float
    is_genuine       : bool | None = None   # ground truth (eval only)


def make_decision(
    fidelity_scores : dict,
    lstm_scores     : dict,
    claimed_subject : str,
) -> AuthDecision:
    """
    Two-gate decision logic from the flowchart.
    """
    thr          = get_fidelity_threshold(claimed_subject)
    fused        = fidelity_scores['fused_score']
    mean_err     = lstm_scores['mean_recon_error']

    # Gate 1: Fidelity High?
    if fused < thr:
        return AuthDecision.REJECT_SESSION

    # Gate 2: Anomaly Low?
    if mean_err <= ANOMALY_THR_STEPUP:
        return AuthDecision.ACCESS_GRANTED
    elif mean_err <= ANOMALY_THR_REJECT:
        return AuthDecision.STEP_UP_AUTH
    else:
        return AuthDecision.REJECT_SESSION


def authenticate(
    claimed_subject : str,
    session_idx     : int,
    actual_subject  : str | None = None,
    noise_sigma     : float = 0.0,
) -> AuthResult:
    """
    Full Phase 6 authentication pipeline for one attempt.
    """
    t0 = time.time()

    # Steps 1-4
    raw_data     = receive_behavioral_data(
                       actual_subject or claimed_subject,
                       session_idx, noise_sigma)
    fft_enc      = fft_encode(raw_data)
    probe_psi_   = generate_quantum_state(raw_data, fft_enc)

    # Step 5
    template_psi_ = load_user_template(claimed_subject)

    # Step 6
    fid_scores   = compute_fidelity_scores(
                       probe_psi_, template_psi_,
                       claimed_subject, fft_enc)

    # Steps 7 & 8
    lstm_scores  = run_lstm_autoencoder(raw_data)

    # Decision
    decision     = make_decision(fid_scores, lstm_scores, claimed_subject)
    elapsed_ms   = (time.time() - t0) * 1000

    return AuthResult(
        subject_id       = claimed_subject,
        session_idx      = session_idx,
        decision         = decision,
        fused_score      = fid_scores['fused_score'],
        fidelity_thr     = get_fidelity_threshold(claimed_subject),
        fidelity_pass    = fid_scores['fused_score'] >= get_fidelity_threshold(claimed_subject),
        mean_recon_error = lstm_scores['mean_recon_error'],
        anomaly_zone     = lstm_scores['anomaly_zone'],
        llr              = fid_scores['llr'],
        fidelity_ip      = fid_scores['fidelity_ip'],
        fidelity_bc      = fid_scores['fidelity_bc'],
        elapsed_ms       = elapsed_ms,
        is_genuine       = (actual_subject == claimed_subject)
                            if actual_subject else None,
    )


