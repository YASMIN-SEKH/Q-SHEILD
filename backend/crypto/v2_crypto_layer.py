# Orchestrates the entire Phase 7 flowchart in a single call.

def monitor_session(
    claimed_subject : str,
    actual_subject  : str,
    session_idx     : int,
    verbose         : bool = True,
) -> SessionState:
    """
    Full Phase 7 continuous authentication loop.
    Processes the given session row-by-row in MONITOR_INTERVAL chunks.

    Returns the final SessionState with full event log.
    """
    # Load the full session data for the ACTUAL subject typing
    full_df = df[
        (df['subject'] == actual_subject) &
        (df['sessionIndex'] == session_idx)
    ][FEATURE_COLS].reset_index(drop=True)

    if len(full_df) == 0:
        raise ValueError(
            f'No data: subject={actual_subject} session={session_idx}')

    # Accumulate rows incrementally (simulate streaming)
    buffer = pd.DataFrame(columns=FEATURE_COLS)
    cursor = 0

    state = SessionState(
        session_id     = str(uuid.uuid4())[:8],
        subject_id     = claimed_subject,
        actual_subject = actual_subject,
    )

    if verbose:
        genuine_label = 'GENUINE' if claimed_subject == actual_subject else 'IMPOSTOR'
        print(f'  Session {state.session_id} | claimed={claimed_subject} '
              f'actual={actual_subject} [{genuine_label}]')
        print(f'  Total rows: {len(full_df)} | '
              f'Interval: {MONITOR_INTERVAL} keystrokes')

    # ── Main monitor loop ────────────────────────────────────
    while is_session_active(state, cursor, len(full_df)):

        # Step 1: Session Active? → already checked by while condition

        # Step 2: Capture Live Behavioral Signals
        new_rows = capture_live_signals(full_df, cursor, MONITOR_INTERVAL)
        cursor  += len(new_rows)
        buffer   = pd.concat([buffer, new_rows], ignore_index=True)
        state.rows_seen = cursor

        if len(buffer) < MIN_WINDOW_ROWS:
            continue   # not enough data yet

        state.check_count += 1
        ts = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.%fZ')

        # Step 3 & 4: Feature Extraction + Behavioral Signature
        sig = generate_behavioral_signature(buffer, claimed_subject)
        if sig is None:
            continue

        # Step 5: Anomaly Detection (EWMA drift)
        drift_info = run_anomaly_detection(state, sig)

        # Step 6: Risk Assessment (only if deviation detected)
        if drift_info['deviation']:
            risk_score, dev_level = assess_risk(drift_info, sig)
        else:
            risk_score = 0.0
            dev_level  = DeviationLevel.NONE

        # Steps 7 & 8: Decision
        action = decide_action(
            state, drift_info['deviation'], risk_score, dev_level,
            sig, claimed_subject, actual_subject)

        # Record event
        evt = MonitorEvent(
            event_id          = str(uuid.uuid4())[:8],
            check_number      = state.check_count,
            timestamp_utc     = ts,
            rows_processed    = cursor,
            fused_score       = sig['fused_score'],
            recon_error       = sig['recon_error'],
            ewma_fidelity     = drift_info['ewma_fidelity'],
            ewma_anomaly      = drift_info['ewma_anomaly'],
            fidelity_drift    = drift_info['fidelity_drift'],
            anomaly_drift     = drift_info['anomaly_drift'],
            deviation_level   = dev_level,
            risk_score        = risk_score,
            action            = action,
            anomaly_zone      = sig['anomaly_zone'],
            is_genuine        = (claimed_subject == actual_subject),
        )
        state.events.append(evt)

        if verbose:
            dev_marker = ('⚠ ' if dev_level != DeviationLevel.NONE else '  ')
            print(f'    {dev_marker}Check #{state.check_count:02d} '
                  f'row={cursor:3d} '
                  f'fid={sig["fused_score"]:.4f} '
                  f'err={sig["recon_error"]:.4f} '
                  f'drift_f={drift_info["fidelity_drift"]:+.4f} '
                  f'risk={risk_score:.2f} '
                  f'→ {action.value}')

        # If session was terminated by re-auth failure, stop
        if not state.is_active:
            if verbose:
                print(f'    ✗ Session terminated after re-auth failure')
            break

    if state.is_active:
        state.is_active = False
        term_evt = MonitorEvent(
            event_id='session_end', check_number=state.check_count+1,
            timestamp_utc=datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.%fZ'),
            rows_processed=cursor,
            fused_score=state.events[-1].fused_score if state.events else 0.0,
            recon_error=state.events[-1].recon_error if state.events else 0.0,
            ewma_fidelity=state.ewma_fidelity or 0.0,
            ewma_anomaly=state.ewma_anomaly or 0.0,
            fidelity_drift=0.0, anomaly_drift=0.0,
            deviation_level=DeviationLevel.NONE,
            risk_score=0.0,
            action=MonitorAction.SESSION_ENDED,
            anomaly_zone='normal',
            is_genuine=(claimed_subject == actual_subject),
        )
        state.events.append(term_evt)

    if verbose:
        print(f'  ── Session ended. Checks={state.check_count} '
              f'Alerts={state.alert_count} '
              f'Locks={state.lock_count} '
              f'ReAuths={state.reauth_count}')

    return state

