# ============================================================
# SECTION 24 — Audit Log Helper (Hash-Chained)
# ============================================================
# Each log row includes:
#   prev_log_hash  — SHA-256 of the previous row (genesis = 64 zeros)
#   row_hash       — SHA-256 of (sequence_no || event_type || subject_id
#                               || outcome || detail || prev_log_hash)
# Tampering with any historical row breaks every subsequent hash.

_GENESIS_HASH = '0' * 64

def _get_prev_hash(conn: sqlite3.Connection) -> tuple[int, str]:
    """Return (next_sequence_no, prev_row_hash)."""
    row = conn.execute(
        'SELECT sequence_no, row_hash FROM audit_log '
        'ORDER BY sequence_no DESC LIMIT 1'
    ).fetchone()
    if row is None:
        return 1, _GENESIS_HASH
    return row['sequence_no'] + 1, row['row_hash']


def _compute_row_hash(seq: int, event_type: str, subject_id: str | None,
                      outcome: str, detail: str, prev_hash: str,
                      created_utc: str) -> str:
    payload = '|'.join([
        str(seq), event_type, subject_id or '', outcome,
        detail, prev_hash, created_utc
    ])
    return hashlib.sha256(payload.encode()).hexdigest()


def write_audit(conn: sqlite3.Connection,
                event_type: str,
                outcome: str,
                subject_id: str | None = None,
                detail: dict | None = None) -> str:
    """Insert one audit log entry; returns log_id."""
    log_id      = str(uuid.uuid4())
    created_utc = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.%fZ')
    detail_json = json.dumps(detail or {})
    seq, prev   = _get_prev_hash(conn)
    row_hash    = _compute_row_hash(seq, event_type, subject_id,
                                    outcome, detail_json, prev, created_utc)
    conn.execute(
        'INSERT INTO audit_log '
        '(log_id, sequence_no, event_type, subject_id, outcome, detail, '
        ' prev_log_hash, row_hash, created_utc) '
        'VALUES (?,?,?,?,?,?,?,?,?)',
        (log_id, seq, event_type, subject_id, outcome,
         detail_json, prev, row_hash, created_utc)
    )
    return log_id


def verify_audit_chain(conn: sqlite3.Connection) -> bool:
    """Walk the entire log and verify every hash link."""
    rows = conn.execute(
        'SELECT * FROM audit_log ORDER BY sequence_no ASC'
    ).fetchall()
    prev_hash = _GENESIS_HASH
    for row in rows:
        expected = _compute_row_hash(
            row['sequence_no'], row['event_type'], row['subject_id'],
            row['outcome'], row['detail'], prev_hash, row['created_utc']
        )
        if expected != row['row_hash']:
            print(f'  [CHAIN BROKEN] at seq={row["sequence_no"]} log_id={row["log_id"]}')
            return False
        prev_hash = row['row_hash']
    return True

