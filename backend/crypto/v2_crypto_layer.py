# SECTION 43 — Step 7: Build LSTM Autoencoder
# ============================================================
# Architecture:
#   Input   : (LSTM_TIMESTEPS, N_FEATURES) rolling window
#   Encoder : LSTM(LSTM_UNITS) → Dense(LSTM_LATENT)  [bottleneck]
#   Decoder : RepeatVector → LSTM(LSTM_UNITS, return_sequences)
#             → TimeDistributed(Dense(N_FEATURES))
#   Loss    : MAE reconstruction error
#
# Trained ONLY on genuine enrollment sessions.
# High reconstruction error → behavioural anomaly → impostor signal.

N_FEAT = len(FEATURE_COLS)

def build_lstm_autoencoder(timesteps: int, n_features: int,
                            units: int, latent: int) -> keras.Model:
    inp = keras.Input(shape=(timesteps, n_features), name='encoder_input')

    # Encoder
    x = layers.LSTM(units, return_sequences=False, name='enc_lstm')(inp)
    x = layers.Dropout(0.1)(x)
    encoded = layers.Dense(latent, activation='relu', name='latent')(x)

    # Decoder
    x = layers.RepeatVector(timesteps, name='repeat')(encoded)
    x = layers.LSTM(units, return_sequences=True, name='dec_lstm')(x)
    x = layers.Dropout(0.1)(x)
    decoded = layers.TimeDistributed(
        layers.Dense(n_features), name='reconstruction')(x)

    model = keras.Model(inp, decoded, name='lstm_autoencoder')
    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=1e-3),
        loss='mae'
    )
    return model


