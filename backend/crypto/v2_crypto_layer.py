# Multi-resolution STFT (nperseg=4,8,16) over each feature column,
# extracting N_STATS_PER_BIN=12 statistics per frequency bin.
# This is the exact same spectral encoding used during enrollment
# (Phase 1 Section 5 → xgb_scaler → LDA projection).
