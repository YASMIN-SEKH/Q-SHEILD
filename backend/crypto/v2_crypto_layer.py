def is_session_active(state: SessionState,
                      current_row: int,
                      total_rows: int) -> bool:
    """
    Step 1 — Session Active?
    Returns False if session is exhausted, explicitly ended,
    or locked after too many failed re-auths.
    """
    if not state.is_active:
        return False
    if current_row >= total_rows:
        return False
    if state.check_count >= MAX_SESSION_CHECKS:
        return False
    return True

