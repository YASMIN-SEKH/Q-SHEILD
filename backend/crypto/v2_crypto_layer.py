# Output: the same xgb_scaler-normalised aggregated vector
# that feeds the LDA projector to build the quantum state.

def fft_encode(session_df: pd.DataFrame) -> dict:
    """
    Step 3 — FFT Encoding.
    Runs multi-resolution STFT on each feature column and
    extracts spectral statistics.

    Returns a dict with:
      'stft_features' : per-resolution spectral feature arrays
      'agg_vector'    : aggregated session vector (pre-scaling)
      'scaled_vector' : xgb_scaler applied (ready for LDA/XGB)
    """
    X = session_df[FEATURE_COLS].values.astype(np.float64) \
        if hasattr(session_df, 'columns') \
        else session_df.values.astype(np.float64)

    stft_features = {}

    for nperseg in NPERSEG_LIST:
        spec_stats = []
        for col_idx in range(X.shape[1]):
            sig = X[:, col_idx]
            _, _, Zxx = scipy.signal.stft(sig, fs=1.0, nperseg=nperseg)
            mag = np.abs(Zxx)   # (freq_bins, time_frames)

            for freq_bin in range(mag.shape[0]):
                row_v = mag[freq_bin, :]
                iqr   = float(np.percentile(row_v, 75) - np.percentile(row_v, 25))
                p     = row_v / (row_v.sum() + 1e-12)
                p     = p[p > 0]
                entr  = float(-np.sum(p * np.log(p + 1e-12)))
                ac    = float(np.corrcoef(row_v[:-1], row_v[1:])[0, 1]) \
                        if len(row_v) > 2 and row_v.std() > 1e-10 else 0.0
                loge  = float(np.log(np.sum(row_v**2) + 1e-12))

                spec_stats.extend([
                    row_v.mean(), row_v.std(), row_v.max(),
                    float(np.sum(row_v**2)),  # energy
                    iqr,
                    float(np.median(row_v)),
                    float(np.percentile(row_v, 10)),
                    float(np.percentile(row_v, 90)),
                    float(row_v.std() / (abs(row_v.mean()) + 1e-10)),  # CV
                    entr, ac, loge,
                ])

        stft_features[f'nperseg_{nperseg}'] = np.array(spec_stats)

    # Aggregated session vector (12 stats × N_FEATURES columns)
    agg_vec    = build_session_feature_vector(session_df)
    scaled_vec = xgb_scaler.transform(agg_vec.reshape(1, -1))[0]

    return {
        'stft_features' : stft_features,
        'agg_vector'    : agg_vec,
        'scaled_vector' : scaled_vec,
    }


