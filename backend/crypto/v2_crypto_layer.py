# ── NIST key/ciphertext sizes ──────────────────────────────────
KEM_PK_BYTES = 1568   # Kyber-1024 public key
KEM_SK_BYTES = 3168   # Kyber-1024 secret key
KEM_CT_BYTES = 1568   # Kyber-1024 ciphertext
KEM_SS_BYTES = 32     # Kyber-1024 shared secret
DSA_PK_BYTES = 2592   # Dilithium-5 verify key
DSA_SK_BYTES = 4864   # Dilithium-5 sign key

# ── ML-KEM wrappers ────────────────────────────────────────────
def kem_generate_keypair():
    """Return (public_key_bytes, secret_key_bytes).
    Stub: pk embedded at sk[:KEM_PK_BYTES] so decapsulate can recover ss.
    (Mirrors real Kyber sk layout: sk_pke || seed || H(pk) || z.)
    """
    if PQC_REAL:
        pk, sk = _ml_kem.generate_keypair()
        return bytes(pk), bytes(sk)
    seed = os.urandom(32)
    pk   = hashlib.sha256(seed + b'qs-pk').digest() + os.urandom(KEM_PK_BYTES - 32)
    sk   = pk + seed + os.urandom(KEM_SK_BYTES - KEM_PK_BYTES - 32)
    return pk, sk

def kem_encapsulate(public_key):
    """Sender — return (ciphertext, shared_secret).
    Stub: nonce masked by hash(pk) so recipient can unmask it with embedded pk.
    """
    if PQC_REAL:
        ct, ss = _ml_kem.encrypt(public_key)
        return bytes(ct), bytes(ss)
    nonce = os.urandom(32)
    ss    = hashlib.sha256(b'qs-ss' + public_key[:32] + nonce).digest()
    mask  = hashlib.sha256(b'qs-mask' + public_key[:32]).digest()
    hdr   = bytes(a ^ b for a, b in zip(nonce, mask))
    return hdr + os.urandom(KEM_CT_BYTES - 32), ss

def kem_decapsulate(secret_key, ciphertext):
    """Recipient — recover shared_secret from ciphertext.
    Stub: extract pk from sk, unmask nonce, recompute ss deterministically.
    """
    if PQC_REAL:
        return bytes(_ml_kem.decrypt(secret_key, ciphertext))
    pk    = secret_key[:KEM_PK_BYTES]
    mask  = hashlib.sha256(b'qs-mask' + pk[:32]).digest()
    nonce = bytes(a ^ b for a, b in zip(ciphertext[:32], mask))
    return hashlib.sha256(b'qs-ss' + pk[:32] + nonce).digest()


# ── ML-DSA wrappers ────────────────────────────────────────────
def dsa_generate_keypair():
    """Return (verify_key_bytes, sign_key_bytes)."""
    if PQC_REAL:
        pk, sk = _ml_dsa.generate_keypair()
        return bytes(pk), bytes(sk)
    return os.urandom(DSA_PK_BYTES), os.urandom(DSA_SK_BYTES)

def dsa_sign(sign_key, message):
    """
    pqcrypto.sign returns signed_msg = signature_bytes || message.
    We strip the appended message and return only the detached signature.
    """
    if PQC_REAL:
        signed = bytes(_ml_dsa.sign(sign_key, message))
        return signed[: len(signed) - len(message)]
    return hashlib.sha512(sign_key[:32] + message).digest()

def dsa_verify(verify_key, message, signature):
    """Return True if ML-DSA signature valid, False otherwise."""
    if PQC_REAL:
        try:
            _ml_dsa.verify(verify_key, signature + message)
            return True
        except Exception:
            return False
    return True   # stub always passes

# ── HKDF-SHA256 (minimal extract+expand) ──────────────────────
def _hkdf(ikm, info=b'qshield-v2-phase4', length=32):
    prk = hashlib.sha256(b'qshield-salt-v2' + ikm).digest()
    okm, prev = b'', b''
    for i in range(1, length // 32 + 2):
        prev = hashlib.sha256(prk + prev + info + bytes([i])).digest()
        okm += prev
    return okm[:length]

# ── Symmetric encryption: AES-256-GCM → XOR-stream fallback ───
def sym_encrypt(key, plaintext):
    """
    Returns opaque blob prefixed with scheme tag:
      b'aes:' + nonce(12) + tag(16) + ciphertext   [AES-GCM]
      b'xor:' + nonce(16) + ciphertext              [fallback]
    """
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
        nonce = os.urandom(12)
        ct    = AESGCM(key).encrypt(nonce, plaintext, None)
        return b'aes:' + nonce + ct
    except ImportError:
        pass
    nonce = os.urandom(16)
    pad, block = b'', hashlib.sha256(key + nonce).digest()
    while len(pad) < len(plaintext):
        pad += hashlib.sha256(block + struct.pack('>I', len(pad))).digest()
    return b'xor:' + nonce + bytes(p ^ k for p, k in zip(plaintext, pad[:len(plaintext)]))

def sym_decrypt(key, blob):
    if blob[:4] == b'aes:':
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
        return AESGCM(key).decrypt(blob[4:16], blob[16:], None)
    nonce, ct = blob[4:20], blob[20:]
    pad, block = b'', hashlib.sha256(key + nonce).digest()
    while len(pad) < len(ct):
        pad += hashlib.sha256(block + struct.pack('>I', len(pad))).digest()
    return bytes(c ^ k for c, k in zip(ct, pad[:len(ct)]))

