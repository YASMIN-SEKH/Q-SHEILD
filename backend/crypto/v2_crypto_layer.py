def run_lstm_autoencoder(
    session_df: pd.DataFrame,
) -> dict:
    """
    Steps 7 & 8 — Run LSTM Autoencoder + Compute Reconstruction Error.

    Returns
    -------
    dict with:
      'sequences'         : rolling windows fed to LSTM
      'recon_errors'      : per-window MAE
      'mean_recon_error'  : scalar anomaly score
      'anomaly_zone'      : 'normal' | 'elevated' | 'high'
    """
    seqs = make_sequences(session_df, LSTM_TIMESTEPS, lstm_scaler)

    if len(seqs) == 0:
        return {
            'sequences': seqs,
            'recon_errors': np.array([]),
            'mean_recon_error': float('inf'),
            'anomaly_zone': 'high',
        }

    errors = reconstruction_error(lstm_ae, seqs)
    mean_err = float(errors.mean())

    if mean_err <= ANOMALY_THR_STEPUP:
        zone = 'normal'
    elif mean_err <= ANOMALY_THR_REJECT:
        zone = 'elevated'
    else:
        zone = 'high'

    return {
        'sequences'        : seqs,
        'recon_errors'     : errors,
        'mean_recon_error' : mean_err,
        'anomaly_zone'     : zone,
    }


